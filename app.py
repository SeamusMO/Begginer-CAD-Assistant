# Jinja2 filter: lightweight OpenSCAD syntax highlighter
# ══════════════════════════════════════════════════════════════════════════════

SCAD_KEYWORDS = {
    "module", "function", "for", "if", "else", "true", "false",
    "include", "use", "let", "each",
}

def _highlight_scad(code: str) -> str:
    """
    Convert a plain SCAD string to HTML with CSS class spans.
    Order matters: comments first, then strings, then keywords/numbers.
    """
    lines = []
    for raw_line in code.split("\n"):
        line = html_lib.escape(raw_line)         # XSS-safe baseline

        # Comments  //...
        line = re.sub(
            r'(//.*?)$',
            r'<span class="sc-comment">\1</span>',
            line
        )

        # Only process non-comment portions for keywords/numbers
        def _process_token(m):
            tok = m.group(0)
            if tok in SCAD_KEYWORDS:
                return f'<span class="sc-keyword">{tok}</span>'
            return tok

        # Keywords (whole words only, skip inside comment spans)
        if 'sc-comment' not in line:
            line = re.sub(r'\b(' + '|'.join(SCAD_KEYWORDS) + r')\b', _process_token, line)

            # Numbers (int / float, not inside words)
            line = re.sub(
                r'(?<![a-zA-Z_])(\d+\.?\d*)',
                r'<span class="sc-number">\1</span>',
                line
            )

            # Module / function names (word immediately before '(')
            line = re.sub(
                r'\b([a-zA-Z_]\w*)\s*(?=\()',
                r'<span class="sc-module">\1</span>',
                line
            )

        lines.append(line)
    return "\n".join(lines)

app.jinja_env.filters["highlight_scad"] = _highlight_scad

